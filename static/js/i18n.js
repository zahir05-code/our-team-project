/* ── 현재 언어 상태 ── */
let _currentLang = localStorage.getItem("athena_lang") || "ko";

/* ── 번역 함수 ── */
function T(key, ...args) {
  const dict = I18N[_currentLang] || I18N["ko"];
  const val  = dict[key] ?? I18N["ko"][key];
  if (typeof val === "function") return val(...args);
  return val ?? key;
}

/* ── 언어 적용 ── */
function applyLang(lang) {
  _currentLang = lang;
  localStorage.setItem("athena_lang", lang);

  // data-i18n 요소 일괄 업데이트
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    const dict = I18N[lang] || I18N["ko"];
    const val  = dict[key] ?? I18N["ko"][key];
    if (typeof val === "string") {
      if (el.dataset.i18nHtml) el.innerHTML = val;
      else el.textContent = val;
    }
  });

  // placeholder 별도 처리
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const key = el.dataset.i18nPh;
    const dict = I18N[lang] || I18N["ko"];
    el.placeholder = dict[key] ?? I18N["ko"][key] ?? "";
  });

  // select option 첫번째 텍스트
  document.querySelectorAll("[data-i18n-opt]").forEach(el => {
    const key = el.dataset.i18nOpt;
    const dict = I18N[lang] || I18N["ko"];
    if (el.options && el.options.length > 0)
      el.options[0].textContent = dict[key] ?? I18N["ko"][key] ?? "";
  });

  // 언어 선택 버튼 활성 상태
  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });

  // HTML lang 속성
  const langMap = { ko:"ko", en:"en", zh:"zh-Hans", ja:"ja", vi:"vi", th:"th", km:"km" };
  document.documentElement.lang = langMap[lang] || lang;

  // 동적 UI (상황 그리드·칩) 갱신 — 이미 렌더링된 경우에만
  const grid = document.getElementById("situationGrid");
  if (grid && grid.children.length > 0 && typeof refreshDynamicUI === "function") {
    refreshDynamicUI();
  }
}

/* ── 초기화 시 언어 복원 ── */
document.addEventListener("DOMContentLoaded", () => {
  applyLang(_currentLang);
});
